/**
 * 输入一个数组ht，其中的每个元素代表一个垂直隔板的高度。数组中的任意两个隔板，以及它们之间的空间可以组成一个容器。
容器的容量等于高度和宽度的乘积（面积），其中高度由较短的隔板决定，宽度是两个隔板的数组索引之差。
请在数组中选择两个隔板，使得组成的容器的容量最大，返回最大容量。
 */
function maxArea(ht) {
    let max = 0;
    let L = 0, R = ht.length - 1;
    while (L < R) {
        const width = R - L;
        const height = Math.min(ht[L], ht[R]);
        max = Math.max(max,width * height);
        if (ht[L] < ht[R]) {
            L++;
        } else {
            R--;
        }
    }
    return max;
}
console.log(maxArea([3, 8, 5, 2, 7, 7, 3, 4])); // (5-1)*7// 28

